"""Build assets/heine-snake-data.js from SCHLANGENFRIST.dst using Heine's own DST decoder.

Usage (from the PFSite folder):
    py tools/build_heine_snake.py <copy-of-SCHLANGENFRIST.dst> [path-to-Heine-repo]

Always pass a COPY of the .dst, never the original on the Desktop.
The Heine decoder is imported from <Heine>/fixtures/tools/dst_decode.py (default I:/Projects/Heine).

Output: window.HEINE_SNAKE with header fields, decoded counts, size, and the stitch
path per thread. Straight-line points are dropped (Ramer-Douglas-Peucker, 0.3 mm) so
every row turn, jump and colour change is kept while the file stays small.
"""

import json
import math
import sys
from pathlib import Path

DST = Path(sys.argv[1])
HEINE = Path(sys.argv[2] if len(sys.argv) > 2 else "I:/Projects/Heine")
OUT = Path(__file__).resolve().parent.parent / "assets" / "heine-snake-data.js"
TOL = 3  # 0.3 mm in DST units (0.1 mm)

sys.path.insert(0, str(HEINE / "fixtures" / "tools"))
import dst_decode  # noqa: E402  (Heine's independent decoder)

# Sewing order confirmed from the Ink/Stitch SVG (document order) and decoded block geometry.
THREADS = [
    {"name": "Grün", "real": "#59950f"},
    {"name": "Rot", "real": "#eb2c13"},
    {"name": "Weiß", "real": "#ffffff"},
]


def rdp(pts, tol):
    """Ramer-Douglas-Peucker on a list of (x, y); keeps first and last point."""
    if len(pts) < 3:
        return pts
    keep = [False] * len(pts)
    keep[0] = keep[-1] = True
    stack = [(0, len(pts) - 1)]
    while stack:
        a, b = stack.pop()
        (ax, ay), (bx, by) = pts[a], pts[b]
        dx, dy = bx - ax, by - ay
        norm = math.hypot(dx, dy)
        best, idx = -1.0, -1
        for i in range(a + 1, b):
            px, py = pts[i]
            d = abs(dy * (px - ax) - dx * (py - ay)) / norm if norm else math.hypot(px - ax, py - ay)
            if d > best:
                best, idx = d, i
        if best > tol:
            keep[idx] = True
            stack.append((a, idx))
            stack.append((idx, b))
    return [p for p, k in zip(pts, keep) if k]


def main():
    header, cmds = dst_decode.decode(DST.read_bytes())
    xs = [c["grid"][0] for c in cmds if "grid" in c]
    ys = [c["grid"][1] for c in cmds if "grid" in c]
    minx, maxx, miny, maxy = min(xs), max(xs), min(ys), max(ys)

    def svg(p):  # DST is Y-up; SVG is Y-down
        return (p[0] - minx, maxy - p[1])

    segs, thread, run, sews, jumps_before, last = [], 0, [], 0, 0, (0, 0)
    counts = {"sew": 0, "jump": 0, "change": 0}
    max_len = 0.0

    def flush():
        nonlocal run, sews, jumps_before
        if run:
            pts = rdp(run, TOL)
            flat = [pts[0][0], pts[0][1]]
            for (x0, y0), (x1, y1) in zip(pts, pts[1:]):
                flat += [x1 - x0, y1 - y0]
            segs.append([thread, jumps_before, sews] + flat)
        run, sews, jumps_before = [], 0, 0

    for c in cmds:
        op = c["op"]
        if op == "sew":
            counts["sew"] += 1
            p = svg(c["grid"])
            max_len = max(max_len, math.hypot(*c["delta"]))
            if not run:
                run.append(svg(last))  # thread is laid from the previous position (Heine D5)
            run.append(p)
            sews += 1
            last = c["grid"]
        elif op == "jump":
            counts["jump"] += 1
            flush()
            jumps_before += 1
            last = c["grid"]
        elif op == "change_thread":
            counts["change"] += 1
            flush()
            thread += 1
            last = [last[0] + c["delta"][0], last[1] + c["delta"][1]]
        elif op == "end":
            flush()
    flush()

    data = {
        "source": header.get("LA", DST.stem) + ".dst",  # name from the file header, not the copy
        "decoder": "Heine fixtures/tools/dst_decode.py",
        "header": {k: header.get(k, "") for k in ("LA", "ST", "CO")},
        "counts": {"sew": counts["sew"], "jump": counts["jump"], "change": counts["change"], "threads": counts["change"] + 1},
        "w": maxx - minx,
        "h": maxy - miny,
        "maxStitchMm": round(max_len / 10, 1),
        "threads": THREADS[: counts["change"] + 1],
        "segs": segs,
    }
    js = "/* Generated by tools/build_heine_snake.py from a copy of SCHLANGENFRIST.dst. Do not edit. */\nwindow.HEINE_SNAKE = " + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n"
    OUT.write_text(js, encoding="utf-8")
    pts = sum((len(s) - 3) // 2 for s in segs)
    print(f"{OUT.name}: {len(js) / 1024:.0f} KB · {len(segs)} segments · {pts} points kept · counts {data['counts']} · size {data['w'] / 10} x {data['h'] / 10} mm · max stitch {data['maxStitchMm']} mm")


if __name__ == "__main__":
    main()
